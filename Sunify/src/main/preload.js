const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('sunifyAPI', {
  minimizeWindow: () => ipcRenderer.send('window-minimize'),
  maximizeWindow: () => ipcRenderer.send('window-maximize'),
  closeWindow: () => ipcRenderer.send('window-close'),
  toggleFullscreen: () => ipcRenderer.send('window-fullscreen'),
  updateDiscordPresence: (playbackData) => ipcRenderer.send('discord-rpc-update', playbackData),
  clearDiscordPresence: () => ipcRenderer.send('discord-rpc-clear'),
  onPlayRequest: (callback) => ipcRenderer.on('sunify-play-request', (_event, request) => callback(request)),
  getDiscordAccountProfile: () => ipcRenderer.invoke('get-discord-account-profile'),
  onDiscordAccountProfile: (callback) => ipcRenderer.on('discord-account-profile', (_event, profile) => callback(profile)),
  chooseMusicFolders: () => ipcRenderer.invoke('choose-music-folders'),
  openDownloadsFolder: () => ipcRenderer.invoke('open-downloads-folder'),
  openCacheFolder: () => ipcRenderer.invoke('open-cache-folder'),
  installUpdateFromUrl: (url) => ipcRenderer.invoke('install-update-from-url', url),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  getDiagnostics: () => ipcRenderer.invoke('get-diagnostics'),
  getSecureAuthValue: (key) => ipcRenderer.sendSync('secure-auth-store:get', key),
  setSecureAuthValue: (key, value) => ipcRenderer.sendSync('secure-auth-store:set', key, value),
  deleteSecureAuthValue: (key) => ipcRenderer.sendSync('secure-auth-store:delete', key),
  updateMiniPlayerSettings: (settings) => ipcRenderer.send('mini-player-settings', settings),
  updateMiniPlayerOpacity: (opacity) => ipcRenderer.send('mini-player-opacity', opacity),
  updateMiniPlayerState: (state) => ipcRenderer.send('mini-player-state', state),
  onMiniPlayerStateRequest: (callback) => ipcRenderer.on('mini-player-state-request', callback),
  onMiniPlayerControl: (callback) => ipcRenderer.on('mini-player-control', (_event, action, value) => callback(action, value)),
});
